/* =========================================================
   THEME
   ========================================================= */

function updateThemeIcon() {

    const isDark =
        document.body.classList.contains("dark");

    themeToggle.textContent =
        isDark ? "☀️" : "🌙";
}


themeToggle.addEventListener(
    "click",
    () => {

        document.body.classList.toggle("dark");

        const isDark =
            document.body.classList.contains("dark");

        localStorage.setItem(
            "theme",
            isDark ? "dark" : "light"
        );

        updateThemeIcon();
    }
);


const savedTheme =
    localStorage.getItem("theme");


if (savedTheme === "dark") {

    document.body.classList.add("dark");
}


updateThemeIcon();


/* =========================================================
   FORMAT TIME
   ========================================================= */

function formatTime(seconds) {

    if (!Number.isFinite(seconds)) {
        return "00:00";
    }

    const minutes =
        Math.floor(seconds / 60);

    const secondsPart =
        Math.floor(seconds % 60);

    return (
        String(minutes).padStart(2, "0") +
        ":" +
        String(secondsPart).padStart(2, "0")
    );
}


/* =========================================================
   PLAY BUTTON
   =========================================================

   IMPORTANT:
   We do NOT use "▶" or "❚❚".

   iOS can display some Unicode symbols as emoji.

   Instead, the icons are HTML elements styled
   with CSS in style.css.
   ========================================================= */

function setPlayButtonState(isPlaying) {

    if (!playPauseBtn) {
        return;
    }

    if (isPlaying) {

        playPauseBtn.innerHTML =
            '<span class="pause-symbol" aria-hidden="true"></span>';

        playPauseBtn.setAttribute(
            "aria-label",
            "إيقاف مؤقت"
        );

    } else {

        playPauseBtn.innerHTML =
            '<span class="play-symbol" aria-hidden="true"></span>';

        playPauseBtn.setAttribute(
            "aria-label",
            "تشغيل"
        );
    }
}


/* =========================================================
   LOAD LISTENING
   ========================================================= */

function loadListening(index) {

    if (
        index < 0 ||
        index >= LISTENING_DATA.length
    ) {
        return;
    }


    currentListeningIndex =
        index;


    const listening =
        LISTENING_DATA[index];


    /* Reset question states */

    answeredQuestions =
        new Array(
            listening.questions.length
        ).fill(false);


    /* Update heading */

    listeningNumber.textContent =
        index + 1;

    audioTitleNumber.textContent =
        index + 1;


    questionCountLabel.textContent =
        `${listening.questions.length} أسئلة`;


    /* Load audio */

    audioPlayer.pause();

    audioPlayer.src =
        listening.audio;

    audioPlayer.load();


    setPlayButtonState(false);


    progressBar.value =
        0;


    currentTime.textContent =
        "00:00";


    duration.textContent =
        "00:00";


    /* Keep selected playback speed */

    audioPlayer.playbackRate =
        Number(speedSelect.value);


    /* Render questions */

    renderQuestions(
        listening.questions
    );


    /*
       IMPORTANT:

       Navigation is updated regardless of whether
       the user answered the questions.
    */

    updateNavigation();
}


/* =========================================================
   RENDER QUESTIONS
   ========================================================= */

function renderQuestions(questions) {

    questionsContainer.innerHTML = "";


    questions.forEach(
        (question, questionIndex) => {

            const card =
                document.createElement("article");

            card.className =
                "question-card";


            const top =
                document.createElement("div");

            top.className =
                "question-top";


            const number =
                document.createElement("div");

            number.className =
                "question-number";

            number.textContent =
                String(
                    questionIndex + 1
                ).padStart(2, "0");


            const questionText =
                document.createElement("h3");

            questionText.className =
                "question-text";

            questionText.textContent =
                question.question;


            top.appendChild(number);

            top.appendChild(questionText);


            const answers =
                document.createElement("div");

            answers.className =
                "answers";


            question.answers.forEach(
                (answer, answerIndex) => {

                    const button =
                        document.createElement("button");

                    button.type =
                        "button";

                    button.className =
                        "answer-btn";

                    button.textContent =
                        answer;


                    button.addEventListener(
                        "click",
                        () => {

                            handleAnswer(
                                questionIndex,
                                answerIndex,
                                card,
                                answers,
                                question
                            );

                        }
                    );


                    answers.appendChild(button);
                }
            );


            const result =
                document.createElement("div");

            result.className =
                "answer-result";

            result.hidden =
                true;


            card.appendChild(top);

            card.appendChild(answers);

            card.appendChild(result);


            questionsContainer.appendChild(card);

        }
    );
}


/* =========================================================
   HANDLE ANSWER
   ========================================================= */

function handleAnswer(
    questionIndex,
    selectedAnswerIndex,
    card,
    answersContainer,
    question
) {

    /*
       Prevent answering the same question twice.
    */

    if (
        answeredQuestions[questionIndex]
    ) {
        return;
    }


    answeredQuestions[questionIndex] =
        true;


    const answerButtons =
        answersContainer.querySelectorAll(
            ".answer-btn"
        );


    answerButtons.forEach(
        (button) => {

            button.disabled =
                true;
        }
    );


    const result =
        card.querySelector(
            ".answer-result"
        );


    const isCorrect =
        selectedAnswerIndex ===
        question.correct;


    /* =====================================================
       CORRECT
       ===================================================== */

    if (isCorrect) {

        totalCorrect++;

        correctCount.textContent =
            totalCorrect;


        answerButtons[
            selectedAnswerIndex
        ].classList.add(
            "correct"
        );


        result.hidden =
            false;

        result.className =
            "answer-result correct-message";


        result.innerHTML = `
            <span class="result-icon">✓</span>
            <span>اجابة صحيحة</span>
        `;

    }


    /* =====================================================
       INCORRECT
       ===================================================== */

    else {

        totalIncorrect++;

        incorrectCount.textContent =
            totalIncorrect;


        answerButtons[
            selectedAnswerIndex
        ].classList.add(
            "incorrect"
        );


        answerButtons[
            question.correct
        ].classList.add(
            "correct-reveal"
        );


        result.hidden =
            false;

        result.className =
            "answer-result incorrect-message";


        result.innerHTML = `
            <span class="result-icon">✕</span>
            <span>اجابة خاطئة</span>
        `;
    }


    /*
       Navigation stays enabled.
    */

    updateNavigation();
}


/* =========================================================
   CHECK ANSWERS
   ========================================================= */

function allQuestionsAnswered() {

    return answeredQuestions.length > 0 &&
        answeredQuestions.every(
            (answered) => answered === true
        );
}


/* =========================================================
   NAVIGATION
   =========================================================

   IMPORTANT:

   The user can move between listenings WITHOUT
   answering the questions.

   Previous:
   - Disabled only on Listening 1.

   Next:
   - Disabled only on Listening 10.
   ========================================================= */

function updateNavigation() {

    const isFirstListening =
        currentListeningIndex === 0;

    const isLastListening =
        currentListeningIndex ===
        LISTENING_DATA.length - 1;


    /*
       PREVIOUS
    */

    previousListeningBtn.disabled =
        isFirstListening;


    /*
       NEXT
    */

    nextListeningBtn.disabled =
        isLastListening;


    /*
       Message
    */

    if (isFirstListening) {

        nextMessage.textContent =
            "يمكنك الانتقال إلى المقطع التالي في أي وقت.";

    } else if (isLastListening) {

        nextMessage.textContent =
            "يمكنك الرجوع إلى المقطع السابق في أي وقت.";

    } else {

        nextMessage.textContent =
            "يمكنك الانتقال بين المقاطع في أي وقت.";
    }


    /*
       Button text
    */

    nextListeningBtn.innerHTML = `
        التالي
        <span>←</span>
    `;


    previousListeningBtn.innerHTML = `
        السابق
        <span>→</span>
    `;
}


/* =========================================================
   NEXT LISTENING
   ========================================================= */

nextListeningBtn.addEventListener(
    "click",
    () => {

        const nextIndex =
            currentListeningIndex + 1;


        /*
           Do NOT check answers here.

           The user is allowed to continue
           without answering anything.
        */

        if (
            nextIndex >=
            LISTENING_DATA.length
        ) {
            return;
        }


        loadListening(
            nextIndex
        );


        window.scrollTo({
            top: 0,
            behavior: "smooth"
        });
    }
);


/* =========================================================
   PREVIOUS LISTENING
   ========================================================= */

previousListeningBtn.addEventListener(
    "click",
    () => {

        const previousIndex =
            currentListeningIndex - 1;


        /*
           Do NOT check answers here.

           The user can go backwards at any time.
        */

        if (
            previousIndex < 0
        ) {
            return;
        }


        loadListening(
            previousIndex
        );


        window.scrollTo({
            top: 0,
            behavior: "smooth"
        });
    }
);


/* =========================================================
   PLAY / PAUSE
   ========================================================= */

playPauseBtn.addEventListener(
    "click",
    () => {

        if (audioPlayer.paused) {

            audioPlayer.play().catch(
                (error) => {

                    console.error(
                        "Audio playback failed:",
                        error
                    );

                }
            );

        } else {

            audioPlayer.pause();
        }
    }
);


/* =========================================================
   AUDIO EVENTS
   ========================================================= */

audioPlayer.addEventListener(
    "play",
    () => {

        setPlayButtonState(true);
    }
);


audioPlayer.addEventListener(
    "pause",
    () => {

        setPlayButtonState(false);
    }
);


audioPlayer.addEventListener(
    "ended",
    () => {

        setPlayButtonState(false);
    }
);


/* =========================================================
   AUDIO PROGRESS
   ========================================================= */

audioPlayer.addEventListener(
    "timeupdate",
    () => {

        if (!audioPlayer.duration) {
            return;
        }


        progressBar.value =
            (
                audioPlayer.currentTime /
                audioPlayer.duration
            ) * 100;


        currentTime.textContent =
            formatTime(
                audioPlayer.currentTime
            );
    }
);


audioPlayer.addEventListener(
    "loadedmetadata",
    () => {

        duration.textContent =
            formatTime(
                audioPlayer.duration
            );

        currentTime.textContent =
            "00:00";

        progressBar.value =
            0;
    }
);


/* =========================================================
   PROGRESS BAR
   ========================================================= */

progressBar.addEventListener(
    "input",
    () => {

        if (!audioPlayer.duration) {
            return;
        }


        audioPlayer.currentTime =
            (
                Number(
                    progressBar.value
                ) / 100
            ) *
            audioPlayer.duration;
    }
);


/* =========================================================
   VOLUME
   ========================================================= */

volumeBar.addEventListener(
    "input",
    () => {

        audioPlayer.volume =
            Number(volumeBar.value);


        if (
            audioPlayer.volume === 0
        ) {

            muteBtn.textContent =
                "🔇";

        } else {

            muteBtn.textContent =
                "🔊";
        }
    }
);


/* =========================================================
   MUTE
   ========================================================= */

let previousVolume = 1;


muteBtn.addEventListener(
    "click",
    () => {

        if (audioPlayer.muted) {

            audioPlayer.muted =
                false;

            audioPlayer.volume =
                previousVolume;

            volumeBar.value =
                previousVolume;

            muteBtn.textContent =
                "🔊";

        } else {

            previousVolume =
                audioPlayer.volume || 1;

            audioPlayer.muted =
                true;

            volumeBar.value =
                0;

            muteBtn.textContent =
                "🔇";
        }
    }
);


/* =========================================================
   PLAYBACK SPEED
   ========================================================= */

speedSelect.addEventListener(
    "change",
    () => {

        audioPlayer.playbackRate =
            Number(
                speedSelect.value
            );
    }
);


/* =========================================================
   RESTART AUDIO
   ========================================================= */

restartAudioBtn.addEventListener(
    "click",
    () => {

        audioPlayer.currentTime =
            0;

        audioPlayer.play().catch(
            () => {}
        );
    }
);


/* =========================================================
   INITIAL LOAD
   ========================================================= */

setPlayButtonState(false);

loadListening(0);
